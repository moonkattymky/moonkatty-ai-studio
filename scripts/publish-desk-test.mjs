// Stage D: Telegram/YouTube desk. No live network. A token never lands in the data dir.
import { createRequire } from 'module';
import fs from 'fs';
import http from 'http';
import os from 'os';
import path from 'path';
process.env.NODE_ENV = 'test';
process.env.STUDIO_FLAVOR = 'test';
delete process.env.STUDIO_TEST_SECURITY_BIN;
const require = createRequire(import.meta.url);
const express = require('express');
const { mountPublishDesk } = require('../lib/publish-desk.js');
const keystore = require('../lib/keystore.js');
let pass = 0, fail = 0;
const t = (n, c, x = '') => { c ? pass++ : fail++; console.log((c ? 'PASS ' : 'FAIL ') + n + (x ? ' — ' + x : '')); };
const TOKEN = '123456789:TESTTOKENVALUE_NOT_A_REAL_SECRET_12345';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pub-'));
let fetches = 0;
const fetchFn = async url => { fetches++; if (String(url).includes('getMe')) return { text: async () => JSON.stringify({ ok: true, result: { id: 1, is_bot: true, username: 'demo_bot' } }) }; return { text: async () => JSON.stringify({ ok: false, description: 'no' }) }; };
const app = express(); app.use(express.json()); app.use((req, res, next) => { req.user = 'igor'; next(); });
mountPublishDesk(app, { dataDir: dir, log() {}, keystore, isTest: true, fetchFn });
const srv = http.createServer(app).listen(0); const B = `http://127.0.0.1:${srv.address().port}`;
const call = async (m, p, b) => { const r = await fetch(B + p, { method: m, headers: { 'content-type': 'application/json' }, body: b ? JSON.stringify(b) : undefined }); return { s: r.status, j: await r.json() }; };
const treeHas = needle => { const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => { const f = path.join(d, e.name); return e.isDirectory() ? walk(f) : [f]; }); return walk(dir).some(f => fs.readFileSync(f, 'utf8').includes(needle)); };
try {
  const st0 = await call('GET', '/api/publish/connectors');
  t('status starts Не подключено', st0.s === 200 && st0.j.telegram.status === 'Не подключено' && st0.j.telegram.connected === false && st0.j.youtube.connected === false && st0.j.publishEnabled === false, JSON.stringify(st0.j.telegram));
  const noKc = await call('POST', '/api/publish/telegram', { token: TOKEN, channel: '@x' });
  t('no keychain: 424 and token not sent to Telegram', noKc.s === 424 && noKc.j.code === 'keychain_unavailable' && noKc.j.connected === false && fetches === 0, noKc.s + ' ' + noKc.j.code);
  t('no keychain: token absent from data dir', !treeHas(TOKEN));
  const noYt = await call('POST', '/api/publish/youtube/client', { client_id: 'client-test.apps.googleusercontent.com', client_secret: 'SECRETVALUE123' });
  t('no keychain: youtube client refused', noYt.s === 424 && noYt.j.connected === false && !treeHas('SECRETVALUE123'));
  const KC = fs.mkdtempSync(path.join(os.tmpdir(), 'pubkc-'));
  process.env.STUDIO_TEST_SECURITY_BIN = path.resolve('scripts/test-fixtures/fake-security.mjs');
  process.env.FAKE_KEYCHAIN_FILE = path.join(KC, 'kc.json');
  process.env.FAKE_KEYCHAIN_ARGV_LOG = path.join(KC, 'argv.log');
  const bad = await call('POST', '/api/publish/telegram', { token: 'not-a-token' });
  t('bad token shape refused before storage', bad.s === 400 && bad.j.connected === false && !fs.existsSync(process.env.FAKE_KEYCHAIN_FILE));
  const ok = await call('POST', '/api/publish/telegram', { token: TOKEN });
  t('live getMe then connected', ok.s === 200 && ok.j.connected === true && ok.j.status === 'Подключено' && ok.j.bot === 'demo_bot' && fetches === 1, JSON.stringify(ok.j));
  t('token is in the fake keychain, not the data dir', fs.readFileSync(process.env.FAKE_KEYCHAIN_FILE, 'utf8').includes(TOKEN) && !treeHas(TOKEN));
  t('argv log has no token', !fs.readFileSync(process.env.FAKE_KEYCHAIN_ARGV_LOG, 'utf8').includes(TOKEN));
  const again = await call('GET', '/api/publish/connectors');
  t('stored check keeps Подключено only with the token', again.j.telegram.connected === true && again.j.telegram.status === 'Подключено' && again.j.youtube.status === 'Не подключено');
  const yt = await call('POST', '/api/publish/youtube/client', { client_id: 'client-test.apps.googleusercontent.com', client_secret: 'SECRETVALUE123' });
  t('youtube client stored but not connected', yt.s === 200 && yt.j.connected === false && yt.j.status === 'Не подключено' && fs.readFileSync(process.env.FAKE_KEYCHAIN_FILE, 'utf8').includes('SECRETVALUE123') && !treeHas('SECRETVALUE123'), JSON.stringify(yt.j));
  const q = await call('POST', '/api/publish/queue', { channel: 'telegram', text: 'Черновик', contentHash: 'abc123' });
  t('queue accepts a draft', q.s === 201 && q.j.status === 'queued' && q.j.contentHash === 'abc123');
  const d0 = await call('POST', '/api/publish/dispatch', { id: q.j.id, contentHash: 'abc123' });
  t('dispatch without owner confirmation is 422', d0.s === 422 && d0.j.code === 'owner_confirmation_required');
  const d1 = await call('POST', '/api/publish/dispatch', { id: q.j.id, contentHash: 'abc123', ownerConfirmed: true });
  t('confirmed dispatch still does not send', d1.s === 403 && d1.j.code === 'publish_not_enabled' && fetches === 1, d1.s + ' ' + d1.j.code);
  const src = fs.readFileSync(new URL('../server.js', import.meta.url), 'utf8');
  const authAt = src.indexOf("req.user = s.user");
  const mountAt = src.indexOf('mountPublishDesk');
  t('route is mounted after API auth', authAt > 0 && mountAt > authAt);
} catch (e) { fail++; console.error(e); } finally { srv.close(); }
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
