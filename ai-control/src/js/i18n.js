let lang = 'ru';
export const LANGS = ['ru', 'en'];
export function setLang(l) { lang = LANGS.includes(l) ? l : 'ru'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function t(key, vars) {
  let s = dict[lang][key] ?? dict.ru[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
/** Localise a { ru, en } object (or pass a plain string through). */
export function L(v) { return v == null ? '' : typeof v === 'object' ? (v[lang] ?? v.ru) : String(v); }
export function ago(a) {
  if (!a) return '';
  if (a.u === 'm') return t('ago.m', { n: a.n });
  if (a.u === 'd') return t('ago.d', { n: a.n });
  if (lang === 'ru') { const n = a.n % 10, nn = a.n % 100; return t(n === 1 && nn !== 11 ? 'ago.h' : n >= 2 && n <= 4 && (nn < 12 || nn > 14) ? 'ago.h2' : 'ago.h5', { n: a.n }); }
  return t('ago.h', { n: a.n });
}
export function money(n, cur = 'USD') {
  const sym = { USD: '$', EUR: '€', ILS: '₪' }[cur] || '$';
  const s = Math.round(n).toLocaleString(lang === 'ru' ? 'ru-RU' : 'en-US').replace(/\u00a0|\u202f|,/g, ' ');
  return sym + s;
}
